                <h2>Top Tourist Attractions</h2>
                <ul>
                    <li><strong>Gateway of India</strong> – Mumbai's most iconic monument overlooking the Arabian
                        Sea. Visitors can also take a ferry ride to the famous Elephanta Caves.</li>

                    <li><strong>Marine Drive</strong> – Popularly known as the "Queen's Necklace," this scenic
                        promenade is the perfect place to enjoy sunsets and evening walks.</li>

                    <li><strong>Elephanta Caves</strong> – A UNESCO World Heritage Site featuring ancient rock-cut
                        caves and magnificent sculptures dedicated to Lord Shiva.</li>

                    <li><strong>Chhatrapati Shivaji Maharaj Terminus (CSMT)</strong> – A UNESCO-listed railway
                        station famous for its Victorian Gothic architecture.</li>

                    <li><strong>Juhu Beach</strong> – One of Mumbai's most popular beaches, known for its lively
                        atmosphere and delicious street food.</li>

                    <li><strong>Haji Ali Dargah</strong> – A famous mosque located in the Arabian Sea, connected by
                        a beautiful walkway during low tide.</li>

                    <li><strong>Siddhivinayak Temple</strong> – One of India's most visited temples dedicated to
                        Lord Ganesha.</li>

                    <li><strong>Bollywood Studios</strong> – Experience the world of Indian cinema by exploring film
                        studios and live shooting locations.</li>
                </ul>

                <h2>Shopping & Street Food</h2>
                <p>
                    Mumbai is a paradise for shopping lovers and food enthusiasts. Explore
                    bustling markets and enjoy some of India's most famous street food.
                </p>

                <ul>
                    <li><strong>Colaba Causeway</strong> – Best for souvenirs, accessories, and fashion shopping.
                    </li>

                    <li><strong>Crawford Market</strong> – A historic market famous for fresh produce, spices, and
                        household items.</li>

                    <li><strong>Chor Bazaar</strong> – One of India's oldest flea markets, perfect for antiques and
                        vintage collectibles.</li>

                    <li><strong>Must-Try Food</strong> – Taste Mumbai's famous Vada Pav, Pav Bhaji, Bhel Puri, Sev
                        Puri, Bombay Sandwich, Misal Pav, and Kulfi.</li>
                </ul>

                <h2>Historical Significance</h2>
                <p>
                    Mumbai has a rich history dating back to ancient times. The city was ruled
                    by various dynasties before coming under Portuguese and later British
                    control. During British rule, Mumbai developed into one of India's most
                    important ports and commercial centers, and today it remains the country's
                    financial and entertainment capital.
                </p>

