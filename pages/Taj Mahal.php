              <h2>Agra Fort</h2>
              <p>Built in the 16th century, the Red Fort of Agra is an outstanding example of Mughal architecture. This UNESCO World Heritage Site served as the main residence of the Mughal emperors and offers a stunning view of the Taj Mahal from its walls.</p>
              
              <h2>Fatehpur Sikri</h2>
              <p>Located 39 km west of Agra, Fatehpur Sikri was built by Emperor Akbar as his imperial capital. This abandoned city is home to several stunning monuments, including the Buland Darwaza, Panch Mahal, and the Tomb of Salim Chishti.</p>
              
              <h2>Sikandra</h2>
              <p>The tomb of Emperor Akbar, located in Sikandra, is a magnificent blend of Hindu, Christian, Islamic, Buddhist, and Jain architectural styles. The surrounding gardens add to its serene beauty.</p>
              
